<b>Treino Cognitivo Online</b><br>
A plataforma digital de atividades online permite que o Neuropsicólogo responsável supervisione e escolha os exercícios de estimulação cognitivas mais apropriadas para cada paciente, de forma padronizada e individualizada.
Os exercícios são nivelados seguindo parâmetros técnicos que permitem adaptar a reabilitação ou estimulação à capacidade cognitiva de cada paciente. São classificados por áreas de intervenção de acordo com a função cognitiva, atividade cotidiana, ou baseando-se em fatores como o nível de dificuldade ou a idade do indivíduo.<br>
<ul>
