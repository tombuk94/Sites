    <li>Atividades práticas para estimular as habilidades cognitivas (atenção, memória, funções executivas e linguagem</li>
</ul>
<b>*A quantidade de sessões e as atividades são planejadas levando em consideração as potencialidades e limitações de cada indivíduo.</b>
